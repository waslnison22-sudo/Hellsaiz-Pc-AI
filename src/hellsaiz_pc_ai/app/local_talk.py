_DEFAULT_RANDOM = random.Random()
_recent: dict[str, int] = {}
_recent_limit = 4


def _normalise(text: str) -> str:
    cleaned = re.sub(r"[^\w\sа-яё]", " ", text.casefold().replace("ё", "е"))
    return re.sub(r"\s+", " ", cleaned).strip()


def matches(text: str) -> list[Intent]:
    """All intents whose patterns appear in the text."""
    normalised = _normalise(text)
    if not normalised:
        return []
    hits: list[Intent] = []
    for intent in INTENTS:
        for pattern in intent.patterns:
            needle = _normalise(pattern)
            if needle and re.search(rf"(?:^|\s){re.escape(needle)}(?:$|\s)", normalised):
                hits.append(intent)
                break
    return hits


def has_local_answer(text: str) -> bool:
    return bool(matches(text))


def reply(text: str, rng: random.Random | None = None) -> str:
    """A natural local reply; never repeats the last few lines for an intent."""
    generator = rng or _DEFAULT_RANDOM
    hits = matches(text)
    if hits:
        intent = generator.choice(hits)
        options = list(intent.replies)
        key = intent.name
    else:
        options = list(GENERIC)
        key = "generic"
    if not options:
        return "Понял. Скажи чуть подробнее."
    recent = _recent.get(key, 0)
    index = generator.randrange(len(options))
    if len(options) > _recent_limit:
        for offset in range(len(options)):
            candidate = (index + offset + recent) % len(options)
            if candidate != recent:
                index = candidate
                break
    _recent[key] = index
    return options[index]


def reset_history() -> None:
    """Forget which replies were used (tests call this for determinism)."""
    _recent.clear()
